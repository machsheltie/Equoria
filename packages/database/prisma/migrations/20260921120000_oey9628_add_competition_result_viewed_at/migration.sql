--    is APPROVED."
--
-- WHAT THIS ADDS
--   1. `competition_results."viewedAt"` — nullable. NULL means the owning player
--      has not opened this result yet. A timestamp is when they did. This is the
--      only real source for the Story 23.4 `check-results` next-action ("results
--      available, not yet viewed", spec priority 2), which the hub endpoint could
--      not emit at all before this column existed.
--   2. `competition_results_horseId_viewedAt_idx` — the index the check-results
--      read uses. That read runs on EVERY hub load and filters
--      `"horseId" IN (<the player's horses>) AND "viewedAt" IS NULL`. The
--      pre-existing `[horseId, score]` index cannot serve the second predicate.
--
-- HOW THIS SQL WAS PRODUCED
--   Generated by Prisma, not hand-written: `prisma migrate dev` could not be used
--   against the local `equoria` database because it reported pre-existing drift
--   (`horses` carries `idx_horses_userid_age`, which migration
--   20260915120000_bebob_drop_redundant_horse_indexes dropped and which
--   backend/services/databaseOptimizationService.mjs re-creates whenever its test
--   callers run — the known, still-open Equoria-9xa92 defect that the bebob header
--   already documents). `migrate dev` offers exactly one remedy for drift,
--   `migrate reset`, which destroys the development database, so it was NOT run.
--   Instead the identical differ was driven against a throwaway shadow database:
--
--     prisma migrate diff --from-migrations prisma/migrations \
--       --to-schema-datamodel prisma/schema.prisma \
--       --shadow-database-url <disposable> --script
--
--   That compares MIGRATION HISTORY (not the drifted live catalog) with the
--   schema, which is the comparison `migrate dev` would have made. Its complete
--   output was the two statements below, in this order, and NOTHING else — in
--   particular no `DROP INDEX` for the raw-SQL runtime indexes or the partial
--   unique indexes Prisma does not own (the Equoria-69gip hazard). The only edit
--   made to the generated script is the backfill UPDATE, inserted between them.
--
-- THE BACKFILL, AND WHY `now()` RATHER THAN NULL OR `createdAt`
--   Every row that predates this column would otherwise read as UNVIEWED, so the
--   first hub load after deployment would tell every existing player that results
--   are waiting for them — a wall of stale check-results nudges for shows that
--   were run and settled weeks ago. The nudge is only meaningful for results the
--   player has genuinely not seen yet, so the cutover declares the entire
--   pre-existing backlog seen and the feature starts prompting only for results
--   produced after deployment.
--
--   `CURRENT_TIMESTAMP` is used rather than `createdAt` deliberately. Nobody
--   actually opened these results, so copying `createdAt` would fabricate a view
--   event at a time when the column did not exist. The migration timestamp states
--   the truth instead: these rows were declared seen at cutover.
--
-- SAFETY ON EXISTING DATA
--   Additive DDL plus one bounded UPDATE of a column that did not exist one
--   statement earlier. No DELETE, no TRUNCATE, no column dropped or retyped, and
--   nothing outside `competition_results` is touched. Old application code
--   coexists with the new schema: a nullable column no existing reader selects,
--   and no existing writer sets, changes no existing behaviour. On a fresh replay
--   the table is empty, so the UPDATE is a no-op and the resulting schema is
--   identical either way.
--
--   Once applied ANYWHERE this file must never be edited again — comments
--   included — because Prisma hashes its raw bytes (Equoria-mxftz).

-- AlterTable
ALTER TABLE "competition_results" ADD COLUMN     "viewedAt" TIMESTAMP(3);

-- Backfill: the pre-existing backlog is declared seen at cutover (see above).
UPDATE "competition_results" SET "viewedAt" = CURRENT_TIMESTAMP WHERE "viewedAt" IS NULL;

-- CreateIndex
CREATE INDEX "competition_results_horseId_viewedAt_idx" ON "competition_results"("horseId", "viewedAt");
